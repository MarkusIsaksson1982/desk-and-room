#!/usr/bin/env python3
"""Generate the dual-mode contrast table from ``tokens.json``.

The table is a design check, not a compliance claim. WCAG 2.x AA is treated as
a design target: normal text is checked at 4.5:1, large text at 3:1, and
non-text UI used as the only indicator at 3:1.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Iterable

ROOT = Path(__file__).resolve().parent.parent
TOKENS_PATH = ROOT / "tokens.json"
OUTPUT_PATH = ROOT / "docs" / "design-system" / "contrast.md"

TEXT_ROLES = ("text", "text-muted", "accent")
NON_TEXT_ROLES = ("focus", "border")
BACKGROUND_ROLES = ("bg", "surface")


def load_tokens(path: Path = TOKENS_PATH) -> dict[str, Any]:
    """Load the token document from JSON."""
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def _channel(value: int) -> float:
    srgb = value / 255.0
    if srgb <= 0.04045:
        return srgb / 12.92
    return ((srgb + 0.055) / 1.055) ** 2.4


def relative_luminance(hex_color: str) -> float:
    """Return WCAG relative luminance for a #RRGGBB or #RGB colour."""
    value = hex_color.strip().lstrip("#")
    if len(value) == 3:
        value = "".join(character * 2 for character in value)
    if len(value) != 6:
        raise ValueError(f"Expected a #RRGGBB or #RGB colour, got {hex_color!r}")
    try:
        red, green, blue = (int(value[index : index + 2], 16) for index in (0, 2, 4))
    except ValueError as error:
        raise ValueError(f"Invalid hex colour: {hex_color!r}") from error
    return (
        0.2126 * _channel(red)
        + 0.7152 * _channel(green)
        + 0.0722 * _channel(blue)
    )


def contrast_ratio(foreground: str, background: str) -> float:
    """Return the WCAG 2.x contrast ratio between two colours."""
    foreground_luminance = relative_luminance(foreground)
    background_luminance = relative_luminance(background)
    lighter = max(foreground_luminance, background_luminance)
    darker = min(foreground_luminance, background_luminance)
    return (lighter + 0.05) / (darker + 0.05)


def status_roles(tokens: dict[str, Any]) -> list[str]:
    """Return the colour roles used by status tokens, sorted by status name."""
    status = tokens.get("status", {})
    roles = [status[name]["color"] for name in sorted(status)]
    return sorted(set(roles))


def required_pairs(tokens: dict[str, Any]) -> Iterable[dict[str, Any]]:
    """Yield every required contrast pair for both modes."""
    colours = tokens["color"]
    modes = tokens["modes"]
    text_roles = list(TEXT_ROLES) + status_roles(tokens)

    for mode_name in sorted(modes):
        mode = modes[mode_name]
        large_text = bool(mode.get("large_text", False))
        for foreground_role in text_roles:
            required = 3.0 if large_text else 4.5
            requirement = "3.0:1" if large_text else "4.5:1"
            for background_role in BACKGROUND_ROLES:
                foreground = colours[foreground_role]
                background = colours[background_role]
                yield {
                    "mode": mode_name,
                    "foreground_role": foreground_role,
                    "foreground": foreground,
                    "background_role": background_role,
                    "background": background,
                    "ratio": contrast_ratio(foreground, background),
                    "required": required,
                    "requirement": requirement,
                    "kind": "large text" if large_text else "text",
                }

        for foreground_role in NON_TEXT_ROLES:
            for background_role in BACKGROUND_ROLES:
                foreground = colours[foreground_role]
                background = colours[background_role]
                yield {
                    "mode": mode_name,
                    "foreground_role": foreground_role,
                    "foreground": foreground,
                    "background_role": background_role,
                    "background": background,
                    "ratio": contrast_ratio(foreground, background),
                    "required": 3.0,
                    "requirement": "3.0:1",
                    "kind": "non-text UI",
                }


def render_markdown(tokens: dict[str, Any]) -> tuple[str, int, int]:
    """Render the contrast table and return (markdown, passes, failures)."""
    rows = list(required_pairs(tokens))
    failures = [row for row in rows if row["ratio"] + 1e-9 < row["required"]]
    passes = len(rows) - len(failures)

    lines = [
        "# Contrast table",
        "",
        "Generated by `scripts/contrast_table.py` from `tokens.json`. Do not edit by hand.",
        "",
        "This is a design check for the light theme, not a compliance claim. WCAG 2.x AA is",
        "treated here as a **design target**: normal text is checked at 4.5:1, large text at",
        "3:1, and non-text UI used as the only indicator at 3:1. Room mode marks its body text",
        "as large (32 px), so the large-text target applies to its text and status-label pairs.",
        "Desk mode uses the normal-text target. The focus ring and border are checked as",
        "non-text UI in both modes.",
        "",
        "| Mode | Foreground | Background | Ratio | Required | Result |",
        "|---|---|---|---:|---:|---|",
    ]

    for row in rows:
        result = "fail" if row in failures else "pass"
        lines.append(
            "| {mode} | `{foreground_role}` ({foreground}) | `{background_role}` "
            "({background}) | {ratio:.2f}:1 | {requirement} | {result} |".format(
                mode=row["mode"],
                foreground_role=row["foreground_role"],
                foreground=row["foreground"],
                background_role=row["background_role"],
                background=row["background"],
                ratio=row["ratio"],
                requirement=row["requirement"],
                result=result,
            )
        )

    lines.extend(
        [
            "",
            f"**Summary:** {len(rows)} pairs checked, {passes} pass, {len(failures)} fail.",
            "",
            "Status is never conveyed by colour alone. Each status also has a distinct shape",
            "and a text label in `tokens.json`; the contrast table checks the colour layer only.",
            "",
        ]
    )

    return "\n".join(lines), passes, len(failures)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate docs/design-system/contrast.md from tokens.json."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if docs/design-system/contrast.md is missing or out of date.",
    )
    args = parser.parse_args(argv)

    try:
        tokens = load_tokens()
        markdown, passes, failures = render_markdown(tokens)
    except (OSError, json.JSONDecodeError, KeyError, TypeError, ValueError) as error:
        print(f"contrast_table: {error}", file=sys.stderr)
        return 1

    relative_output = OUTPUT_PATH.relative_to(ROOT)

    if args.check:
        if not OUTPUT_PATH.exists():
            print(
                f"{relative_output} is missing; run python3 scripts/contrast_table.py",
                file=sys.stderr,
            )
            return 1
        if OUTPUT_PATH.read_text(encoding="utf-8") != markdown:
            print(
                f"{relative_output} is out of date; run python3 scripts/contrast_table.py",
                file=sys.stderr,
            )
            return 1
        print(f"{relative_output} is up to date.")
        return 0 if failures == 0 else 1

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(markdown, encoding="utf-8")
    print(
        f"Wrote {relative_output}: {passes} pass, {failures} fail."
    )
    return 0 if failures == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
