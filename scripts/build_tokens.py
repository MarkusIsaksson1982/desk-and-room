#!/usr/bin/env python3
"""Build ``styles/tokens.css`` from ``tokens.json``.

``tokens.json`` is the source of truth. The generated CSS is deterministic:
object keys are sorted and no timestamp or environment data is written.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Iterable

ROOT = Path(__file__).resolve().parent.parent
TOKENS_PATH = ROOT / "tokens.json"
OUTPUT_PATH = ROOT / "styles" / "tokens.css"


def load_tokens(path: Path = TOKENS_PATH) -> dict[str, Any]:
    """Load the token document from JSON."""
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def _css_value(value: Any) -> str:
    """Return a stable CSS representation for a scalar token value."""
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        return value
    raise TypeError(f"Unsupported token value: {value!r}")


def _flatten(prefix: str, value: Any) -> Iterable[tuple[str, Any]]:
    """Yield dotted/grouped token paths and scalar values in sorted order."""
    if isinstance(value, dict):
        for key in sorted(value):
            child = f"{prefix}-{key}" if prefix else str(key)
            yield from _flatten(child, value[key])
    else:
        yield prefix, value


def _properties(group: str, value: dict[str, Any]) -> list[str]:
    """Turn a token group into sorted CSS custom-property declarations."""
    declarations = []
    for name, token_value in _flatten(group, value):
        declarations.append(f"  --{name}: {_css_value(token_value)};")
    declarations.sort()
    return declarations


def _status_properties(status: dict[str, Any]) -> list[str]:
    """Create colour, shape and label properties for each status."""
    declarations = []
    for name in sorted(status):
        entry = status[name]
        colour_role = entry["color"]
        declarations.append(
            f"  --status-{name}-color: var(--color-{colour_role});"
        )
        declarations.append(
            f"  --status-{name}-shape: {json.dumps(entry['shape'])};"
        )
        declarations.append(
            f"  --status-{name}-label: {json.dumps(entry['label'])};"
        )
    declarations.sort()
    return declarations


def _mode_properties(mode: dict[str, Any]) -> list[str]:
    """Create the mode-specific custom properties for one mode."""
    declarations = []
    for key in sorted(mode):
        name = key.replace("_", "-")
        declarations.append(f"  --mode-{name}: {_css_value(mode[key])};")
    declarations.sort()
    return declarations


def render_css(tokens: dict[str, Any]) -> str:
    """Render the complete, deterministic token stylesheet."""
    lines = [
        "/* Generated by scripts/build_tokens.py from tokens.json. Do not edit by hand. */",
        "",
    ]

    root_declarations: list[str] = []
    for group in ("color", "space", "type", "radius", "focus", "motion"):
        value = tokens.get(group)
        if isinstance(value, dict):
            root_declarations.extend(_properties(group, value))

    status = tokens.get("status")
    if isinstance(status, dict):
        root_declarations.extend(_status_properties(status))

    root_declarations.sort()
    lines.append(":root {")
    lines.extend(root_declarations)
    lines.append("}")
    lines.append("")

    modes = tokens.get("modes")
    if isinstance(modes, dict):
        for mode_name in sorted(modes):
            lines.append(f'[data-mode="{mode_name}"] {{')
            lines.extend(_mode_properties(modes[mode_name]))
            lines.append("}")
            lines.append("")

    reduced = "0ms"
    motion = tokens.get("motion")
    if isinstance(motion, dict):
        reduced = _css_value(motion.get("reduced", "0ms"))

    lines.append("@media (prefers-reduced-motion: reduce) {")
    lines.append("  :root {")
    for name in ("fast", "normal", "slow"):
        lines.append(f"    --motion-{name}: {reduced};")
    lines.append("  }")
    lines.append("}")
    lines.append("")

    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate styles/tokens.css from tokens.json."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if styles/tokens.css is missing or out of date.",
    )
    args = parser.parse_args(argv)

    try:
        tokens = load_tokens()
        css = render_css(tokens)
    except (OSError, json.JSONDecodeError, KeyError, TypeError) as error:
        print(f"build_tokens: {error}", file=sys.stderr)
        return 1

    relative_output = OUTPUT_PATH.relative_to(ROOT)

    if args.check:
        if not OUTPUT_PATH.exists():
            print(
                f"{relative_output} is missing; run python3 scripts/build_tokens.py",
                file=sys.stderr,
            )
            return 1
        if OUTPUT_PATH.read_text(encoding="utf-8") != css:
            print(
                f"{relative_output} is out of date; run python3 scripts/build_tokens.py",
                file=sys.stderr,
            )
            return 1
        print(f"{relative_output} is up to date.")
        return 0

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(css, encoding="utf-8")
    print(f"Wrote {relative_output}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
